// Rebuilds Sources/AppleDeviceImages/MacFamilies.swift: for every `MacNN,N` model this Mac's CoreTypes
// knows, the family folder under which Find My's CDN has its image.
//
//     swift Scripts/ScanMacFamilies.swift
//
// Run it on the newest macOS after new Macs ship.

import Foundation

let families = ["MacBookPro", "MacBookAir", "Macmini", "iMac", "MacStudio", "MacPro", "MacBook", "Mac"]

func macModels() throws -> [String] {
    let library = URL(fileURLWithPath: "/System/Library/CoreServices/CoreTypes.bundle/Contents/Library")
    var models = Set<String>()
    for bundle in try FileManager.default.contentsOfDirectory(at: library, includingPropertiesForKeys: nil) {
        let plist = bundle.appendingPathComponent("Contents/Info.plist")
        guard let data = try? Data(contentsOf: plist),
              let info = try? PropertyListSerialization.propertyList(from: data, format: nil) as? [String: Any],
              let types = info["UTExportedTypeDeclarations"] as? [[String: Any]] else { continue }
        for type in types {
            let tags = (type["UTTypeTagSpecification"] as? [String: Any])?["com.apple.device-model-code"]
            let codes = (tags as? [String]) ?? (tags as? String).map { [$0] } ?? []
            for code in codes where code.hasPrefix("Mac") {
                let numbers = code.dropFirst(3).split(separator: ",")
                if numbers.count == 2, numbers.allSatisfy({ Int($0) != nil }) { models.insert(code) }
            }
        }
    }
    return models.sorted { $0.compare($1, options: .numeric) == .orderedAscending }
}

final class NoRedirects: NSObject, URLSessionTaskDelegate {
    func urlSession(_ session: URLSession, task: URLSessionTask, willPerformHTTPRedirection response: HTTPURLResponse,
                    newRequest request: URLRequest) async -> URLRequest? { nil }
}

func exists(_ family: String, _ model: String) async -> Bool {
    let url = URL(string: "https://statici.icloud.com/fmipmobile/deviceImages-9.0/\(family)/\(model)/online-infobox__3x.png")!
    var request = URLRequest(url: url)
    request.httpMethod = "HEAD"
    let response = try? await URLSession.shared.data(for: request, delegate: NoRedirects()).1
    return (response as? HTTPURLResponse)?.statusCode == 200
}

let models = try macModels()
var found: [(String, String)] = []
await withTaskGroup(of: (String, String?).self) { group in
    for model in models {
        group.addTask {
            for family in families where await exists(family, model) { return (model, family) }
            return (model, nil)
        }
    }
    for await (model, family) in group {
        if let family { found.append((model, family)) } else { print("no image: \(model)") }
    }
}
found.sort { $0.0.compare($1.0, options: .numeric) == .orderedAscending }

let entries = found.map { "        \"\($0.0)\": \"\($0.1)\"," }.joined(separator: "\n")
let source = """
// Generated by Scripts/ScanMacFamilies.swift; don't edit.

extension Product {
    /// Find My's family folder for each `MacNN,N` model.
    static let macFamily: [String: String] = [
\(entries)
    ]
}

"""
let output = URL(fileURLWithPath: #filePath).deletingLastPathComponent()
    .appendingPathComponent("../Sources/AppleDeviceImages/MacFamilies.swift").standardizedFileURL
try source.write(to: output, atomically: true, encoding: .utf8)
print("\(found.count) of \(models.count) Mac models → \(output.path)")
